/**
 * Возвращает текст промпта VOICE_NER.
 * Используется Nodul для извлечения сущностей из голосовых сообщений.
 *
 * @returns {string} текст промпта
 */
function getVoiceNerPrompt() {
  return PromptTemplates.VOICE_NER;
}

/**
 * Сохраняет промпт VOICE_NER в папку Voice/Prompts/ для чтения Nodul.
 * 
 * Nodul читает этот промпт при старте сценария Voice Input.
 * Это позволяет обновлять промпт без изменения Nodul.
 * 
 * @returns {GoogleAppsScript.Drive.File}
 */
function saveVoiceNerPromptToDrive_() {
  const promptText = getVoiceNerPrompt();
  const fileName = PROJECT_FILES.VOICE_NER_PROMPT;
  
  // Получаем папку Voice/Prompts/
  const promptsFolder = getVoicePromptsFolder_();
  
  // Сохраняем промпт с перезаписью
  const file = saveFileWithOverwrite_(
    promptsFolder,
    fileName,
    promptText,
    MimeType.PLAIN_TEXT
  );
  
  Logger.log('Voice NER prompt saved: ' + file.getUrl());
  return file;
}

/**
 * Публичная функция для ручного обновления промпта в Drive.
 * Может вызываться из меню Google Sheets.
 */
function updateVoiceNerPromptInDrive() {
  try {
    const file = saveVoiceNerPromptToDrive_();
    showInfo_(
      'Промпт VOICE_NER обновлён в Drive.\n\n' +
      'Файл: ' + file.getName() + '\n' +
      'URL: ' + file.getUrl() + '\n\n' +
      'Nodul прочитает обновлённый промпт при следующем запуске.'
    );
  } catch (error) {
    showError_('Ошибка обновления промпта: ' + error.message);
    throw error;
  }
}

